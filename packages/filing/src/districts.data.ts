/**
 * Every appraisal district in Texas, as the state itself names them.
 *
 * Generated, not typed by hand, and generated from two Comptroller sources
 * because neither one carries the whole answer.
 *
 * **The names come from the MAP reports.** The Comptroller reviews every
 * appraisal district under Tax Code 5.102(a) on a two-year cycle and publishes
 * one PDF per district; the review page names the district on the line under
 * "Final Methods and Assistance Program Review". The 2024 cohort is 128
 * districts and the 2025 cohort is 125, and together they are 253 — which is
 * also how many appraisal districts Texas has, so the two cohorts cover the
 * state exactly once with nothing left over.
 * https://comptroller.texas.gov/taxes/property-tax/map/2024/
 * https://comptroller.texas.gov/taxes/property-tax/map/2025/
 *
 * **The addresses come from the county directory**, one page per county, which
 * is the only place the state publishes where to send the paper.
 * https://comptroller.texas.gov/taxes/property-tax/county-directory/
 *
 * That split is the whole reason this file exists in this shape: the county
 * directory has the contact block and never prints the district's name — its
 * own page title for Harris County says "Harris Appraisal District", which is
 * not what that district has been called since 2023.
 *
 * **Six strings were corrected, and only these six.** The rule applied is that
 * the words "Appraisal District" may be repaired and the district-specific part
 * of the name may not, so nothing here is a guess about what a district calls
 * itself:
 *
 *   Baylor    "Baylor County Apprasial District"
 *   Coleman   "Coleman County Appraisal Distict"
 *   Donley    "Donley County Appraisl District"      (the same report prints
 *                                                     the correct spelling on
 *                                                     its next page)
 *   Roberts   "Roberts County Appraisal Disrict"
 *   Johnson   "Central Appraisal District Of Johnson County"
 *   Taylor    "Central Appraisal District Of Taylor County"
 *
 * The last two are the Comptroller title-casing a preposition. Bell County's
 * report, from the same corpus and the same template, prints "Tax Appraisal
 * District of Bell County" with a small "of", so the lower-case form is the
 * one this source itself uses.
 *
 * Addresses, phones and websites go stale in a way names do not, so each record
 * carries the day the Comptroller last touched that county's entry rather than
 * presenting all 253 as equally fresh. Where a district serves two counties the
 * later of the two dates is kept. Those dates are normalised to ISO, which for
 * two of them means reading past the state's own formatting: Crockett is
 * published as "06/8/2017" and McMullen as "02/18/25".
 */

/** One county a district appraises, with the state's three-digit code. */
export interface AppraisalDistrictCounty {
  /** The jurisdiction id this repo uses elsewhere: `tx-` and the county. */
  id: string;
  /** The county's name, without the word "County". */
  name: string;
  /** The Comptroller's county number, 001-254. Stable; the names are not. */
  code: string;
}

export interface AppraisalDistrictRecord {
  /** The district's own name. This is what goes in field one of a form. */
  name: string;
  /**
   * Every county it appraises. Exactly one for 252 of the 253 districts;
   * Potter-Randall is the reason this is a list.
   */
  counties: readonly AppraisalDistrictCounty[];
  /** Where filings go. Tax Code 1.08 makes the postmark the filing date. */
  mailingAddress: readonly string[];
  phone: string | null;
  website: string | null;
  /** The Comptroller's own "Last Updated" on the directory entry, as ISO. */
  directoryUpdated: string;
}

